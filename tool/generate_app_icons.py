#!/usr/bin/env python3
"""Generates the launcher icons (Neon = default, Flat, Grayscale) from one
spec (D50, D60).

Writes, relative to the project root:
- Adaptive icons (Android 8+): vector foregrounds, a shared monochrome
  layer (Android 13 themed icons) and background colours.
- PNG fallbacks for Android 7 (mipmap-*dpi).
- Settings previews (assets/app_icons/*.png).
- The F-Droid store icon (fastlane/.../images/icon.png, Neon).

Run after changing the design:  python3 tool/generate_app_icons.py
Needs Pillow.
"""

from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "android/app/src/main/res"

# Adaptive icon canvas is 108 x 108 dp; launchers may mask everything
# outside a centred circle of 66 dp, so the grid (with glow) stays inside it.
CANVAS = 108
TILE_W, TILE_H, GAP, RADIUS = 12.0, 11.0, 8 / 3, 2.5
COLS, ROWS = 4, 2
GRID_W = COLS * TILE_W + (COLS - 1) * GAP
GRID_H = ROWS * TILE_H + (ROWS - 1) * GAP
X0 = (CANVAS - GRID_W) / 2
Y0 = (CANVAS - GRID_H) / 2

# Activity palette (lib/models/activity_colors.dart); slot 6 is active.
COLORS = [
    "F44336", "FF9800", "FFC107", "2196F3",
    "9C27B0", "4CAF50", "00BCD4", "E91E63",
]
ACTIVE = 5

VARIANTS = {
    # name: (background, resource suffix)
    "neon": ("05070A", ""),
    "flat": ("1B2624", "_flat"),
    # Flat's design with every colour turned to its grey (D60).
    "grayscale": ("1C1C1C", "_grayscale"),
}
RUNNING_RING = "E8F5E9"  # flat: ring around the active tile


def gray(color):
    """[color] as the grey of equal luminance (Rec. 709, as in the app)."""
    r, g, b = (int(color[i:i + 2], 16) for i in (0, 2, 4))
    v = round(0.2126 * r + 0.7152 * g + 0.0722 * b)
    return f"{v:02X}" * 3


def tile_rect(i, grow=0.0):
    col, row = i % COLS, i // COLS
    x = X0 + col * (TILE_W + GAP) - grow
    y = Y0 + row * (TILE_H + GAP) - grow
    return x, y, TILE_W + 2 * grow, TILE_H + 2 * grow, RADIUS + grow


def pause_bars(i):
    """Two bars of the pause symbol, centred in tile [i]."""
    x, y, w, h, _ = tile_rect(i)
    bw, bh, gap = 1.4, 4.6, 1.4
    cx, cy = x + w / 2, y + h / 2
    return [
        (cx - gap / 2 - bw, cy - bh / 2, bw, bh, 0.3),
        (cx + gap / 2, cy - bh / 2, bw, bh, 0.3),
    ]


def shapes(variant):
    """Layers as (kind, rect, colour, alpha, stroke_width), back to front."""
    if variant == "grayscale":
        return [(k, r, gray(c), a, s) for k, r, c, a, s in shapes("flat")]
    bg = VARIANTS[variant][0]
    out = []
    for i, c in enumerate(COLORS):
        if i == ACTIVE:
            continue
        if variant == "neon":
            out.append(("fill", tile_rect(i, -0.4), c, 0.10, 0))
            out.append(("stroke", tile_rect(i, -0.4), c, 1.0, 0.8))
        else:
            out.append(("fill", tile_rect(i), c, 0.34, 0))
    a = COLORS[ACTIVE]
    if variant == "neon":
        for grow, alpha in ((3.2, 0.10), (2.1, 0.18), (1.0, 0.32)):
            out.append(("fill", tile_rect(ACTIVE, grow), a, alpha, 0))
    else:
        out.append(("stroke", tile_rect(ACTIVE, 1.5), RUNNING_RING, 1.0, 1.0))
    out.append(("fill", tile_rect(ACTIVE), a, 1.0, 0))
    for bar in pause_bars(ACTIVE):
        out.append(("fill", bar, bg, 1.0, 0))
    return out


# ---------------------------------------------------------------- vectors


def f(v):
    return f"{v:.3f}".rstrip("0").rstrip(".")


def rrect_path(x, y, w, h, r):
    return (
        f"M{f(x + r)},{f(y)} H{f(x + w - r)} "
        f"A{f(r)},{f(r)} 0 0 1 {f(x + w)},{f(y + r)} V{f(y + h - r)} "
        f"A{f(r)},{f(r)} 0 0 1 {f(x + w - r)},{f(y + h)} H{f(x + r)} "
        f"A{f(r)},{f(r)} 0 0 1 {f(x)},{f(y + h - r)} V{f(y + r)} "
        f"A{f(r)},{f(r)} 0 0 1 {f(x + r)},{f(y)} Z"
    )


def vector(paths):
    body = "\n".join(paths)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_app_icons.py; do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{body}
</vector>
"""


def vector_path(kind, rect, color, alpha, stroke):
    d = rrect_path(*rect)
    if kind == "fill":
        return (
            f'    <path android:fillColor="#{color}" '
            f'android:fillAlpha="{f(alpha)}"\n        android:pathData="{d}" />'
        )
    return (
        f'    <path android:strokeColor="#{color}" '
        f'android:strokeAlpha="{f(alpha)}" android:strokeWidth="{f(stroke)}"\n'
        f'        android:pathData="{d}" />'
    )


def monochrome():
    """Themed icon: outlines, the active tile filled with a cut-out pause."""
    paths = []
    for i in range(len(COLORS)):
        if i != ACTIVE:
            paths.append(
                vector_path("stroke", tile_rect(i, -0.4), "000000", 1, 0.9)
            )
    # Even-odd fill cuts the pause bars out of the active tile.
    d = " ".join(rrect_path(*r) for r in [tile_rect(ACTIVE), *pause_bars(ACTIVE)])
    paths.append(
        '    <path android:fillColor="#000000" android:fillType="evenOdd"\n'
        f'        android:pathData="{d}" />'
    )
    return vector(paths)


def adaptive(variant):
    suffix = VARIANTS[variant][1]
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_app_icons.py; do not edit by hand. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher{suffix}_background" />
    <foreground android:drawable="@drawable/ic_launcher{suffix}_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""


# ---------------------------------------------------------------- bitmaps

SUPERSAMPLE = 8


def render(variant, size):
    """Full-bleed square of the visible 72 dp centre, rounded like a legacy
    launcher icon."""
    bg = VARIANTS[variant][0]
    big = size * SUPERSAMPLE
    scale = big / 72  # the central 72 of 108 dp is what launchers show
    off = 18

    def px(rect):
        x, y, w, h, r = rect
        return (
            [(x - off) * scale, (y - off) * scale,
             (x - off + w) * scale, (y - off + h) * scale],
            r * scale,
        )

    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    for kind, rect, color, alpha, stroke in shapes(variant):
        layer = Image.new("RGBA", (big, big), (0, 0, 0, 0))
        rgb = tuple(int(color[i:i + 2], 16) for i in (0, 2, 4))
        box, r = px(rect)
        d = ImageDraw.Draw(layer)
        if kind == "fill":
            d.rounded_rectangle(box, r, fill=rgb + (round(alpha * 255),))
        else:
            w = stroke * scale
            # Pillow strokes inwards; widen the box so the line is centred.
            box = [box[0] - w / 2, box[1] - w / 2, box[2] + w / 2, box[3] + w / 2]
            d.rounded_rectangle(
                box, r + w / 2, outline=rgb + (round(alpha * 255),),
                width=round(w),
            )
        img = Image.alpha_composite(img, layer)

    base = Image.new("RGBA", (big, big), tuple(int(bg[i:i + 2], 16) for i in (0, 2, 4)) + (255,))
    base = Image.alpha_composite(base, img)
    mask = Image.new("L", (big, big), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, big - 1, big - 1], big * 0.22, fill=255)
    out = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    out.paste(base, (0, 0), mask)
    return out.resize((size, size), Image.LANCZOS)


DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def main():
    (RES / "drawable").mkdir(exist_ok=True)
    anydpi = RES / "mipmap-anydpi-v26"
    anydpi.mkdir(exist_ok=True)
    assets = ROOT / "assets/app_icons"
    assets.mkdir(parents=True, exist_ok=True)

    colors = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tool/generate_app_icons.py; do not edit by hand. -->",
        "<resources>",
    ]
    for variant, (bg, suffix) in VARIANTS.items():
        name = f"ic_launcher{suffix}"
        paths = [vector_path(*s) for s in shapes(variant)]
        (RES / f"drawable/{name}_foreground.xml").write_text(vector(paths))
        (anydpi / f"{name}.xml").write_text(adaptive(variant))
        colors.append(f'    <color name="{name}_background">#FF{bg}</color>')
        for density, size in DENSITIES.items():
            render(variant, size).save(RES / f"mipmap-{density}/{name}.png")
        render(variant, 192).save(assets / f"{variant}.png")
    # Store listing icon (F-Droid reads fastlane metadata).
    store = ROOT / "fastlane/metadata/android/en-US/images"
    store.mkdir(parents=True, exist_ok=True)
    render("neon", 512).save(store / "icon.png")
    colors.append("</resources>")
    (RES / "values/ic_launcher_colors.xml").write_text("\n".join(colors) + "\n")
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(monochrome())


if __name__ == "__main__":
    main()
